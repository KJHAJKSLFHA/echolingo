const DICT = { zh: ZH, en: EN, es: ES };
const LS_LANG = 'echolingo.lang';
const listeners = new Set();

let lang = 'zh';

function detect() {
  try {
    const saved = localStorage.getItem(LS_LANG);
    if (saved && DICT[saved]) return saved;
  } catch {}
  const n = (navigator.language || 'zh').toLowerCase();
  if (n.startsWith('zh')) return 'zh';
  if (n.startsWith('es')) return 'es';
  return 'en';
}

/** 三语轮换顺序：中文 → English → Español → 中文 */
export const LANG_CYCLE = ['zh', 'en', 'es'];
export const nextLang = (cur) => LANG_CYCLE[(LANG_CYCLE.indexOf(cur) + 1) % LANG_CYCLE.length];
/** 顶栏那颗按钮上的短标签（显示的是「按一下会切到哪种」） */
export const LANG_SHORT = { zh: '中', en: 'EN', es: 'ES' };

export function getLang() { return lang; }

const htmlLang = (l) => (l === 'zh' ? 'zh-CN' : l === 'es' ? 'es' : 'en');

export function initLang() {
  lang = detect();
  document.documentElement.lang = htmlLang(lang);
  applyI18n();
}

export function setLang(next) {
  if (!DICT[next] || next === lang) return;
  lang = next;
  try { localStorage.setItem(LS_LANG, lang); } catch {}
  document.documentElement.lang = htmlLang(lang);
  applyI18n();
  listeners.forEach((fn) => { try { fn(lang); } catch (e) { console.error(e); } });
}

export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

export function t(key, vars) {
  const table = DICT[lang] || ZH;
  let s = table[key];
  if (s === undefined) s = ZH[key];
  if (s === undefined) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
  return s;
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((n) => { n.innerHTML = t(n.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-ph]').forEach((n) => { n.placeholder = t(n.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach((n) => { n.title = t(n.dataset.i18nTitle); });
  document.title = t('app.title');
  const md = document.querySelector('meta[name="description"]');
  if (md) md.setAttribute('content', t('app.desc'));
}
